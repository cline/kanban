export const translations = {
	en,
	zh,
} satisfies Record<AppLanguage, Record<TranslationKey, string>>;

export function isAppLanguage(value: string | null | undefined): value is AppLanguage {
	return APP_LANGUAGES.some((language) => language.id === value);
}

export function getLanguageOptionKey(language: AppLanguage): TranslationKey {
	return languageOptionKeys[language];
}

export function translate(language: AppLanguage, key: TranslationKey, values: TranslationValues = {}): string {
	const template = translations[language][key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
	return template.replace(/\{(\w+)\}/g, (match, valueKey: string) => {
		const value = values[valueKey];
		return value === undefined ? match : String(value);
	});
}
